async function generate() {
  const workbook = new ExcelJS.Workbook();
  const sheet    = workbook.addWorksheet('Batches');

  // Define columns (sets header row)
  sheet.columns = Object.keys(ROWS[0]).map((key) => ({ header: key, key, width: 30 }));

  // Add data rows
  ROWS.forEach((row) => sheet.addRow(row));

  await workbook.xlsx.writeFile(OUTPUT_PATH);
  console.log(`[generateSample] Written ${ROWS.length} rows to ${OUTPUT_PATH}`);
}

generate().catch((err) => { console.error(err); process.exit(1); });
